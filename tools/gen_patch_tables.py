"""Generates a C++ patch table (src/generated/*.inc) from an analysis TSV.

usage: python gen_patch_tables.py <table.tsv> <decrypted NieRAutomata.exe> <decrypted NieRAutomataCompat.exe> <out.inc> <Prefix>

The TSV columns are: name, steam, compat, primitive, sig_off, ins_len, disp_off,
opcode, replace_len, instruction, formula, signature, verified.
A signature may be "<steam sig> || <compat sig>" when the two builds differ.
Every signature is re-checked to match exactly once in its executable, and the
original bytes at each patch site are embedded (with a mask over bytes that differ
between the two builds, i.e. relocated displacements) so the DLL can refuse to
patch code it does not recognise. Needs `pip install pefile`.
"""
import re
import sys

import pefile

tsv, exe, exe2, out, prefix = sys.argv[1:6]


def load(path):
    pe = pefile.PE(path, fast_load=True)
    img = pe.get_memory_mapped_image()
    text = next(s for s in pe.sections if s.Name.startswith(b'.text'))
    return img, text.VirtualAddress, img[text.VirtualAddress:text.VirtualAddress + text.Misc_VirtualSize]


images = [load(exe), load(exe2)]


def find(sig, which):
    if len(sig.split()) > 160:  # Pattern::bytes in src/memory.h
        raise SystemExit('signature for %s is longer than 160 bytes' % row['name'])
    image, base, code = images[which]
    rx = re.compile(b''.join(b'.' if t == '??' else re.escape(bytes([int(t, 16)])) for t in sig.split()), re.S)
    hits = [m.start() + base for m in rx.finditer(code)]
    if len(hits) != 1:
        raise SystemExit('signature for %s matches %d times in exe %d' % (row['name'], len(hits), which))
    return hits[0]


def cbytes(b):
    return '{' + ', '.join('0x%02X' % x for x in b) + '}'


def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"' if s else 'nullptr'


def ident(name):
    return re.sub(r'\W', '_', name)


def scale(formula):
    if 'lerparg' in formula:
        return 'Scale::Lerp', 0.0  # lerp of the runtime argument
    m = re.match(r'(lerp|pow|lin)\s+live\b', formula)
    if m:
        return 'Scale::' + m.group(1).capitalize(), 'NAN'  # tuning value re-read from the operand every frame
    f = formula.split('(')[0].strip()
    m = re.match(r'(lerp|pow|lin|sq|inv)\s+(-?[0-9.e-]+)', f)
    if m:
        return 'Scale::' + m.group(1).capitalize(), float(m.group(2))
    if re.search(r'\*=\s*e\b', formula):
        return 'Scale::Lin', 1.0
    m = re.search(r'\(1-([0-9.]+)\^e\)/([0-9.]+)', formula)
    if m:
        return 'Scale::LerpRatio', round(1 - float(m.group(1)), 6)
    raise SystemExit('unknown formula: ' + formula)


cols = None
consts, doubles, args, vecs, sites = [], [], [], [], []
for line in open(tsv, encoding='utf-8'):
    line = line.rstrip('\n')
    if not line:
        continue
    if cols is None:
        cols = line.split('\t')
        continue
    row = dict(zip(cols, line.split('\t')))
    kind, off, name = row['primitive'], int(row['sig_off']), row['name']
    sigs = [s.strip() for s in row['signature'].split('||')]
    sig, alt = sigs[0], (sigs[1] if len(sigs) > 1 else '')
    site = find(sig, 0) + off
    site2 = find(alt or sig, 1) + off
    img, img2 = images[0][0], images[1][0]
    if kind in ('SCALE_CONST', 'SCALE_CONST_DOUBLE'):
        ln, disp = int(row['ins_len']), int(row['disp_off'])
        sk, base = scale(row['formula'])
        literal = base if isinstance(base, str) else repr(base) + ('' if kind == 'SCALE_CONST_DOUBLE' else 'f')
        line = '    {%s, %s, %s, %d, %s, %d, %d, %d, %s, %s},' % (
            cstr(name), cstr(sig), cstr(alt), off, cbytes(img[site:site + disp]), disp, disp, ln, sk, literal)
        (doubles if kind == 'SCALE_CONST_DOUBLE' else consts).append(line)
    elif kind == 'SCALE_ARG_CALL':
        reg = int(re.search(r'xmm(\d+)', row['formula']).group(1))
        sk, base = scale(row['formula'])
        args.append('    {%s, %s, %s, %d, %d, %s, %sf},' % (cstr(name), cstr(sig), cstr(alt), off, reg, sk, repr(base)))
    elif kind == 'SCALE_VEC_RESULT_CALL':
        vecs.append('    {%s, %s, %s, %d},' % (cstr(name), cstr(sig), cstr(alt), off))
    else:
        n = int(row['replace_len'] or 0) or int(row['ins_len'])
        a, b = img[site:site + n], img2[site2:site2 + n]
        mask = sum(1 << i for i in range(n) if a[i] == b[i])
        sites.append('static const SigSite k%s_%s = {%s, %s, %s, %d, %s, %d, 0x%Xull};' % (
            prefix, ident(name), cstr(name), cstr(sig), cstr(alt), off, cbytes(a), n, mask))

with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// Generated by tools/gen_patch_tables.py from %s - do not edit.\n\n' % tsv.replace('\\', '/').split('/')[-1])
    for typ, rows, suffix in (('ScaledConstPatch', consts, 'ScaledConsts'), ('ScaledDoublePatch', doubles, 'ScaledDoubles'),
                              ('ArgCallPatch', args, 'ArgCalls'), ('VecCallPatch', vecs, 'VecCalls')):
        if rows:
            f.write('static const %s k%s%s[] = {\n%s\n};\n\n' % (typ, prefix, suffix, '\n'.join(rows)))
    f.write('\n'.join(sites) + '\n')
print('%s: %d scaled constants, %d doubles, %d arg calls, %d vec calls, %d custom sites' % (
    out, len(consts), len(doubles), len(args), len(vecs), len(sites)))
